"""Generation checks must detect removed module outputs without deleting user files."""

import sys

import pytest

from scripts import sync_module_requirements as sync


@pytest.mark.parametrize("check", [False, True])
def test_orphan_generated_file_is_reported(tmp_path, monkeypatch, check):
    monkeypatch.setattr(sync, "ROOT", tmp_path)
    monkeypatch.setattr(sync, "generated", lambda: {"core.txt": "current\n"})
    monkeypatch.setattr(sys, "argv", ["sync", *(["--check"] if check else [])])
    requirements = tmp_path / "requirements"
    (requirements / "modules").mkdir(parents=True)
    (requirements / "core.txt").write_text("current\n")
    orphan = requirements / "modules" / "removed.txt"
    orphan.write_text(
        "# Generated by scripts/sync_module_requirements.py; edit module manifests.\nold-package\n"
    )
    with pytest.raises(SystemExit, match="Orphan generated dependency file"):
        sync.main()
    assert orphan.exists()


@pytest.mark.parametrize("check", [False, True])
def test_unmanaged_files_are_preserved(tmp_path, monkeypatch, check):
    monkeypatch.setattr(sync, "ROOT", tmp_path)
    monkeypatch.setattr(sync, "generated", lambda: {"core.txt": "current\n"})
    monkeypatch.setattr(sys, "argv", ["sync", *(["--check"] if check else [])])
    requirements = tmp_path / "requirements"
    requirements.mkdir()
    (requirements / "core.txt").write_text("current\n")
    custom = requirements / "constraints.txt"
    custom.write_text("local-package==1\n")
    sync.main()
    assert custom.read_text() == "local-package==1\n"
